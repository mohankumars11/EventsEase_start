/**
 * Sanity check at import time.
 *
 * Two failure modes are worth failing the build over rather than shipping: a
 * theme filed under a family that does not exist (it would silently vanish
 * from the page — no tab renders it), and a duplicate id (two themes would
 * share a cart line and the second would never be addable). Both are the kind
 * of mistake that survives review because nothing throws.
 */
;(() => {
  const families = new Set(DECOR_FAMILIES.map(f => f.id))
  const seen = new Set()
  const problems = []
  for (const theme of DECOR_THEME_CATALOGUE) {
    if (!families.has(theme.family)) problems.push(`${theme.id}: unknown family "${theme.family}"`)
    if (seen.has(theme.id)) problems.push(`${theme.id}: duplicate id`)
    seen.add(theme.id)
  }
  if (problems.length) {
    throw new Error(`decorThemes: ${problems.length} problem(s)\n  - ${problems.join('\n  - ')}`)
  }
})()

export const DECOR_THEME_BY_ID = Object.fromEntries(
  DECOR_THEME_CATALOGUE.map(t => [t.id, t])
)

/** family id → its themes, in catalogue order. */
export const THEMES_BY_FAMILY = Object.fromEntries(
  DECOR_FAMILIES.map(f => [f.id, DECOR_THEME_CATALOGUE.filter(t => t.family === f.id)])
)

/**
 * What one setup costs, at this scale and headcount.
 *
 * Returns the parts as well as the total because the summary panel itemises
 * them — "installation ₹18,000, table work ₹6,000" is a figure somebody can
 * argue with, and ₹24,000 alone is one they can only accept or leave.
 */
export function themeCost(theme, scaleId, guestCount) {
  const scale = DECOR_SCALE_BY_ID[scaleId] ?? DECOR_SCALE_BY_ID.standard
  if (!theme) return { installation: 0, tableWork: 0, total: 0, scale }
  const guests = Number(guestCount) || scale.typicalGuests
  const installation = round10(theme.base * scale.factor)
  const tableWork = round10((theme.perGuest ?? 0) * guests * scale.tableFactor)
  return { installation, tableWork, total: installation + tableWork, scale, guests }
}

/** The cheapest this setup can be booked for — the "from" on its card. */
export function themeFrom(theme) {
  const home = DECOR_SCALE_BY_ID.home
  return round10(theme.base * home.factor) + round10((theme.perGuest ?? 0) * home.typicalGuests * home.tableFactor)
}

/** Free-text search across name, blurb, tags and what it is best for. */
export function searchThemes(query) {
  const q = query.trim().toLowerCase()
  if (q.length < 2) return DECOR_THEME_CATALOGUE
  return DECOR_THEME_CATALOGUE.filter(t =>
    t.name.toLowerCase().includes(q) ||
    t.blurb.toLowerCase().includes(q) ||
    t.tags?.some(tag => tag.toLowerCase().includes(q)) ||
    t.bestFor?.some(b => b.toLowerCase().includes(q))
  )
}
