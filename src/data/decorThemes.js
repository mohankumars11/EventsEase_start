// Every decoration setup we can actually build, named the way a customer asks
// for one.
//
// ── Why this file exists ────────────────────────────────────────────────
// decorPackages.js answers "how much decor" — five levels from a styled corner
// to a marquee — and DECOR_THEMES in that file answers "what colour". Neither
// answers the question people actually walk in with, which is a *thing*:
//
//   "I want a marigold temple setup for the griha pravesh."
//   "Jungle safari, my son turns four."
//   "A glass mandap, and phoolon ki chadar for the bride's entry."
//   "Haldi in the morning — the yellow one with the matkas."
//
// A palette is not a setup. Somebody who taps "Theme Decoration" and is shown
// thirteen colour swatches has been answered with a paint chart when they asked
// for a room. So this is the catalogue of setups: what it is, what gets
// installed, what it costs, and which occasion it belongs to.
//
// ── How it is organised ─────────────────────────────────────────────────
// Ten families, because "decoration" spans a ₹3,500 candlelit table and a
// ₹4,00,000 marquee, and putting them in one flat list makes both look wrong.
// A family is how a customer narrows before they choose — ritual, kids,
// wedding, corporate — not how a decorator organises a warehouse.
//
// Coverage is deliberately pan-India rather than Bengaluru-only. Sambramo
// pilots in Karnataka, but the families who book it are Tamil, Telugu,
// Malayali, Marathi, Bengali, Punjabi, Marwari and Konkani, and a catalogue
// that offers a marigold mandap but not a gaye holud or a phulkari sangeet is
// telling half of them we do not do their function.
//
// ── How a theme is priced ───────────────────────────────────────────────
// Same shape as decorPackages.js, and for the same reason: a backdrop is a
// backdrop whether eighty or eight hundred people look at it, but centrepieces,
// chair work and pathway flowers are per table.
//
//   cost = base × scale.factor  +  perGuest × guests × scale.tableFactor
//
// `base` is the installation at Standard scale (a hall of roughly 150–250).
// `perGuest` is the table and seating work. The scale is the customer's own
// answer to "how big is the room", so the same theme honestly quotes a home
// living room and a kalyana mantapa without pretending they are the same job.
//
// ── The standing caveat ─────────────────────────────────────────────────
// Researched Bengaluru / Mysore / metro-average market estimates, pre-launch,
// with no signed decorator behind any of them. Every surface that renders one
// of these numbers labels it an estimate. Re-check against real rate cards
// before anybody is held to one.

