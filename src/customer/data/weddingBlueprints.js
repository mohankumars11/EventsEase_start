/**
 * Indian Weddings & Traditional Ceremonies — one blueprint per occasion.
 *
 * Nineteen functions, and the hardest thing about them is that no two
 * families do the same one the same way. So the rule running through
 * every record here is the one the brief states and the templates did
 * not keep: **nothing about a family's tradition is ever inferred.**
 *
 *   · A practitioner is asked for, never assumed — including at a
 *     Haldi, a Muhurtham and a Griha Pravesh, where the shared template
 *     made one essential.
 *   · The auspicious time is the family's. We never calculate one; we
 *     ask what they were given and plan around it (GIVEN_TIME).
 *   · The ritual sequence is the family's. We arrange the room, the
 *     food, the flowers and the photographs around whatever they do.
 *   · The ceremony materials are the family's list, not a generic one.
 *   · A cocktail party is not assumed to involve alcohol, and a baraat
 *     is not assumed to involve a horse.
 *   · A ceremony has moments a camera should not be in. PHOTO_LIMITS
 *     is a rule passed to the photographer, not a preference.
 *
 * Where the brief and the existing template disagree, the brief wins
 * and the reason is written on the line.
 *
 * Everything else — the builders, the repeating questions, the trade
 * words — is in data/blueprintKit.js.
 */
