/**
 * Religious, Cultural & Festival Events — one blueprint per occasion.
 *
 * Twenty-four festivals, and the thing that makes them different from
 * every other category is that most of them scale from one family's
 * living room to ten thousand people on a public ground. The same name
 * covers both, so the FIRST question is almost always who this is for
 * (PUBLIC_SCALE) — and the answer is what turns crowd management, first
 * aid, permissions and sanitation on. A home Diwali is never offered a
 * security detail; a community Navratri always is.
 *
 * The safeguards the brief names, kept as rules rather than prose:
 *
 *   · Nothing about a family's faith, region, community or practice is
 *     ever inferred. The customer tells us or we do not ask.
 *   · A practitioner is requested, never assumed — at every one of these.
 *   · Timings are the family's or the committee's. We never calculate
 *     a muhurtham, a sunset or a prayer time.
 *   · Fireworks, effects, immersion and anything with a flame are only
 *     ever offered where they were explicitly selected, and always with
 *     the permission question attached.
 *   · A sacred practice is not entertainment, and a community's own
 *     seva is not a service we sell them.
 *
 * Builders and the repeating questions live in data/blueprintKit.js.
 */
