/**
 * Personal Celebrations & Life Milestones — one blueprint per occasion.
 *
 * occasions.js says WHICH celebrations exist and points each at a shared
 * template (templates.js: must / often / extra). A template is a family
 * resemblance: `babyRite` covers a naming, a cradle and a rice-feeding at
 * once, `gathering` covers a family reunion and a Friday meet-up. That is
 * the right grain for 131 templates and the wrong grain for a plan the
 * customer reads — a reunion and a meet-up do not want the same questions,
 * and three baby rites are not one ceremony.
 *
 * This file is the other grain: all 31 occasions in the `life` category,
 * each with its own words, its own questions and its own mapping. Nothing
 * here invents a service — every `trade` is a registry id (data/trades.js),
 * checked at import. An idea with no trade behind it is an `experience`:
 * it goes in the brief the masters read, and never pretends to be bookable.
 *
 *   hook / statement   what the customer reads at the top of their plan
 *   ask                the questions Event Details adds for this occasion
 *   plan               trade → classification, words and conditions
 *   addons             "Make it even more special" — never a duplicate
 *   toolkit            which free digital features this occasion turns on
 *   timeline           before / during / after
 *   checklist          what "ready" means for this occasion
 *
 * ── What the conditions are ─────────────────────────────────────────
 * Clauses are data, not functions, so a blueprint can be versioned, sent
 * to the server and diffed. lib/occasionPlan.js evaluates them. Every
 * clause is a FACT the customer gave us — an answer or an event detail —
 * never a guess about who they are. See occasionPlan.js for the grammar.
 *
 * ── Three corrections this file makes to the templates ──────────────
 *  1. A priest is never assumed. babyRite and housewarming carry
 *     priest_rituals in `must`; the spec (and Mohan) are explicit that a
 *     family chooses its own ceremony, so here it is CONDITIONAL on the
 *     family asking for one, and the ritual materials follow the same ask.
 *  2. A bachelor/bachelorette party is never assumed to mean a bar and a
 *     DJ. `bachelor` has both in `must`; here they wait for the style the
 *     customer picked.
 *  3. A memorial is never sold entertainment, and its photography waits
 *     for the family to ask for it in words.
 */
