#!/usr/bin/env node
/**
 * The full master dish catalogue, compact, for the menu card's "Swap" and
 * "Add a dish" (Mohan, 2026-11-13: "we already have 2000+ dishes — provide
 * the swapping options from that entire catalogue").
 *
 *   node scripts/build-master-dishes.mjs
 *
 * Reads scripts/data/master-dishes-live.json (the PostgREST cache that
 * scripts/build-menu-catalogue.mjs refreshes) and writes
 * src/customer/data/masterDishes.generated.js:
 *
 *   MASTER = [[id, name, diet, section, cuisine], …]
 *
 * `section` is the menu course the dish belongs to (the Menu Studio's own
 * section ids), from the catalogue's category prefix. `diet` is the
 * catalogue's suggested diet; a dish with none is left out of every
 * vegetarian list, because unreviewed is not veg. Bottled water, packaged
 * juice and packed snacks are not menu dishes and are dropped.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const rows = JSON.parse(readFileSync('scripts/data/master-dishes-live.json', 'utf8'))
const DROP = new Set(['bev_water', 'bev_packaged_juice', 'ad_packed'])
const SECTION = cat => {
  const c = String(cat ?? '')
  if (c === 'ds_ice_cream') return 'icecream'
  if (c === 'ac_salad') return 'salads'
  if (c === 'ad_live_counter') return 'live'
  if (c === 'sp_rasam') return 'curries'
  if (/^bev_(mocktail|fresh_juice|traditional|buttermilk_lassi|coconut|shake|milk)/.test(c)) return 'welcome'
  if (/^bev_/.test(c)) return 'beverages'
  return ({ ds: 'desserts', gr: 'curries', rc: 'rice', ac: 'sides', br: 'breads', st: 'starters', ch: 'starters', bf: 'mains', dr: 'sides', ml: 'mains', sp: 'soups', ad: 'special' })[c.split('_')[0]] ?? 'special'
}
const DIET = d => ({ veg: 'veg', vegan: 'veg', jain: 'veg', non_veg: 'non_veg', egg: 'egg' })[d] ?? null
const out = rows.filter(d => d.name && !DROP.has(d.category_id)).map(d => [d.id, d.name, DIET(d.suggested_diet), SECTION(d.category_id), (d.cuisine_ids ?? [])[0] ?? null])
out.sort((a, b) => a[1].localeCompare(b[1]))
writeFileSync('src/customer/data/masterDishes.generated.js',
  `/* Generated by scripts/build-master-dishes.mjs from the live master dish catalogue — do not edit.\n   MASTER[i] = [id, name, diet (veg | non_veg | egg | null = not reviewed), menu section, first cuisine id] */\n` +
  `export const MASTER = ${JSON.stringify(out)}\n`)
const by = {}
for (const d of out) by[d[2] ?? 'unreviewed'] = (by[d[2] ?? 'unreviewed'] ?? 0) + 1
console.log(`${out.length} dishes`, by)
