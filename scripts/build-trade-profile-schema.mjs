#!/usr/bin/env node
/**
 * Phase 2: generate the typed trade-profile schema from the field map.
 *
 *   node scripts/build-trade-profile-schema.mjs
 *
 * ══════════════════════════════════════════════════════════════════════
 * WHY GENERATED
 * ══════════════════════════════════════════════════════════════════════
 *
 * 34 profile tables and 24 catalogue child tables, ~490 columns. Hand
 * writing that is a transcription exercise with no upside and a long
 * tail of silent typos — a column misspelled against its field key does
 * not fail, it just never receives an answer.
 *
 * The map in docs/partner-onboarding-field-map.json is itself generated
 * from src/data/trades/*.js, so the chain from the question a partner
 * answers to the column it lands in is mechanical end to end.
 *
 * ══════════════════════════════════════════════════════════════════════
 * SPLIT INTO PARTS, BECAUSE THESE ARE PASTED BY HAND
 * ══════════════════════════════════════════════════════════════════════
 *
 * Migrations here go into the Supabase SQL editor by hand. One wall of
 * SQL creating 58 tables is a bad thing to paste: a partial apply
 * leaves the schema half-built with no record of where it stopped. So
 * the output is several numbered files, each independently re-runnable,
 * each ending with a verification SELECT that says what it created.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const MAP = JSON.parse(readFileSync(join(ROOT, 'docs/partner-onboarding-field-map.json'), 'utf8'))
const OUT = join(ROOT, 'supabase/migrations')

/* Postgres reserved words that would need quoting as a column name.
   Rather than quote every identifier — which makes every later query
   fragile to a missing quote — the few that collide get a `_value`
   suffix, recorded in the column comment so the mapping stays visible. */
const RESERVED = new Set([
  'all', 'and', 'any', 'array', 'as', 'asc', 'case', 'cast', 'check', 'column',
  'constraint', 'default', 'desc', 'distinct', 'do', 'else', 'end', 'false',
  'for', 'from', 'grant', 'group', 'having', 'in', 'initially', 'into', 'limit',
  'not', 'null', 'offset', 'on', 'only', 'or', 'order', 'primary', 'references',
  'returning', 'select', 'session_user', 'some', 'table', 'then', 'to', 'true',
  'union', 'unique', 'user', 'using', 'when', 'where', 'window', 'with',
])
const colName = key => (RESERVED.has(key) ? `${key}_value` : key)

const BATCH = 6                       // trades per migration part
const START_NUMBER = 173              // 172 is the highest written so far

const banner = (n, title) => `-- ══════════════════════════════════════════════════════════════════════
-- ${n} · ${title}
-- ══════════════════════════════════════════════════════════════════════
--
-- APPLY BY HAND. Generated by scripts/build-trade-profile-schema.mjs
-- from docs/partner-onboarding-field-map.json. Do not edit directly —
-- regenerate, or the file and the field map drift apart silently.
--`

function profileTable(trade) {
  const t = trade.id
  const table = `partner_${t}_profiles`
  const rows = trade.rows.filter(r => r.section_kind === 'screen')
  const lines = []

  lines.push(`-- ── ${t} ──────────────────────────────────────────────`)
  lines.push(`CREATE TABLE IF NOT EXISTS public.${table} (`)
  lines.push(`  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),`)
  lines.push(`  vendor_id   UUID NOT NULL REFERENCES public.vendors(id) ON DELETE CASCADE,`)
  /* The profile belongs to a LISTING, not just a partner: a partner may
     hold more than one listing in the same trade. Nullable while the
     answers are still a draft and no service row exists yet. */
  lines.push(`  service_id  UUID REFERENCES public.vendor_services(id) ON DELETE CASCADE,`)
  lines.push(`  trade_id    TEXT NOT NULL DEFAULT '${t}' CHECK (trade_id = '${t}'),`)
  lines.push(`  schema_version INTEGER NOT NULL DEFAULT 1,`)
  for (const r of rows) {
    const c = colName(r.field_key)
    lines.push(`  ${c.padEnd(28)} ${r.sql_type},`)
  }
  lines.push(`  source_specs JSONB,`)
  lines.push(`  backfilled_at  TIMESTAMPTZ,`)
  lines.push(`  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),`)
  lines.push(`  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()`)
  lines.push(`);`)
  lines.push('')
  /* One profile per listing. Partial, because service_id is null while
     the listing is still a draft and several drafts may coexist. */
  lines.push(`CREATE UNIQUE INDEX IF NOT EXISTS uq_${t}_profile_service`)
  lines.push(`  ON public.${table} (service_id) WHERE service_id IS NOT NULL;`)
  lines.push(`CREATE INDEX IF NOT EXISTS idx_${t}_profile_vendor ON public.${table} (vendor_id);`)
  lines.push('')
  for (const r of rows) {
    const c = colName(r.field_key)
    const note = c === r.field_key ? '' : ` (field key "${r.field_key}", renamed: reserved word)`
    lines.push(`COMMENT ON COLUMN public.${table}.${c} IS`)
    lines.push(`  ${sqlStr(`${r.label}${r.required ? ' [required]' : ''}${note}`)};`)
  }
  lines.push('')
  lines.push(rls(table))
  return { table, sql: lines.join('\n'), columns: rows.length }
}

function catalogueTable(trade) {
  const t = trade.id
  const rows = trade.rows.filter(r => r.section_kind === 'catalogue')
  if (!rows.length) return null
  const table = `partner_${t}_items`
  const lines = []
  lines.push(`-- ${t}: repeating catalogue items (${rows[0].section})`)
  lines.push(`CREATE TABLE IF NOT EXISTS public.${table} (`)
  lines.push(`  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),`)
  lines.push(`  vendor_id   UUID NOT NULL REFERENCES public.vendors(id) ON DELETE CASCADE,`)
  lines.push(`  service_id  UUID REFERENCES public.vendor_services(id) ON DELETE CASCADE,`)
  lines.push(`  position    INTEGER NOT NULL DEFAULT 0,`)
  for (const r of rows) lines.push(`  ${colName(r.field_key).padEnd(28)} ${r.sql_type},`)
  lines.push(`  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),`)
  lines.push(`  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()`)
  lines.push(`);`)
  lines.push(`CREATE INDEX IF NOT EXISTS idx_${t}_items_service ON public.${table} (service_id, position);`)
  lines.push('')
  lines.push(rls(table))
  return { table, sql: lines.join('\n'), columns: rows.length }
}

const sqlStr = s => `'${String(s).replace(/'/g, "''")}'`

/* The partner owns the row; operators see everything. Mirrors the
   policy shape already used by vendor_services and vendor_documents. */
function rls(table) {
  return [
    `ALTER TABLE public.${table} ENABLE ROW LEVEL SECURITY;`,
    ``,
    `DROP POLICY IF EXISTS ${table}_owner ON public.${table};`,
    `CREATE POLICY ${table}_owner ON public.${table} FOR ALL TO authenticated`,
    `  USING (EXISTS (SELECT 1 FROM public.vendors v WHERE v.id = ${table}.vendor_id AND v.profile_id = auth.uid()))`,
    `  WITH CHECK (EXISTS (SELECT 1 FROM public.vendors v WHERE v.id = ${table}.vendor_id AND v.profile_id = auth.uid()));`,
    ``,
    `DROP POLICY IF EXISTS ${table}_operator ON public.${table};`,
    `CREATE POLICY ${table}_operator ON public.${table} FOR ALL TO authenticated`,
    `  USING (public.caller_is_operator()) WITH CHECK (public.caller_is_operator());`,
    ``,
  ].join('\n')
}

// ── emit ─────────────────────────────────────────────────────────────
mkdirSync(OUT, { recursive: true })
for (const f of readdirSync(OUT)) {
  if (/^\d+_trade_profiles_part\d+\.sql$/.test(f)) unlinkSync(join(OUT, f))
}

const trades = MAP.trades.filter(t => t.rows.some(r => r.section_kind === 'screen'))
const skipped = MAP.trades.filter(t => !t.rows.some(r => r.section_kind === 'screen')).map(t => t.id)

let n = START_NUMBER, part = 1, written = []
for (let i = 0; i < trades.length; i += BATCH) {
  const slice = trades.slice(i, i + BATCH)
  const blocks = []
  const made = []
  for (const t of slice) {
    const p = profileTable(t); blocks.push(p.sql); made.push(p.table)
    const c = catalogueTable(t); if (c) { blocks.push(c.sql); made.push(c.table) }
  }
  const file = `${n}_trade_profiles_part${part}.sql`
  const body = [
    banner(n, `Typed trade profiles — part ${part} of ${Math.ceil(trades.length / BATCH)}`),
    `-- Trades in this part: ${slice.map(t => t.id).join(', ')}`,
    `--`,
    `-- Re-runnable. Creates ${made.length} tables. Verification at the end.`,
    ``,
    `BEGIN;`,
    ``,
    ...blocks,
    `COMMIT;`,
    ``,
    `-- ── verify ───────────────────────────────────────────────────────`,
    `-- Expect ${made.length} rows.`,
    `SELECT table_name, (SELECT count(*) FROM information_schema.columns c`,
    `         WHERE c.table_schema = 'public' AND c.table_name = t.table_name) AS columns`,
    `  FROM information_schema.tables t`,
    ` WHERE table_schema = 'public' AND table_name IN (${made.map(sqlStr).join(', ')})`,
    ` ORDER BY table_name;`,
    ``,
  ].join('\n')
  writeFileSync(join(OUT, file), body)
  written.push({ file, tables: made.length, trades: slice.length })
  n += 1; part += 1
}


// ── runtime config for the console ───────────────────────────────────
/* The console has to render 34 different tables without a 490-row doc
   in the bundle, and without building a table name from anything a user
   typed. This emits an explicit, server-authored allowlist: trade id ->
   table name and column list. A trade not in this map has no workspace,
   which is the safety property section 4.3 asks for. */
const RUNTIME = join(ROOT, 'src/config/tradeProfileSchema.js')
const compact = {}
for (const t of MAP.trades) {
  const profile = t.rows.filter(r => r.section_kind === 'screen')
  if (!profile.length) continue
  const items = t.rows.filter(r => r.section_kind === 'catalogue')
  compact[t.id] = {
    table: `partner_${t.id}_profiles`,
    itemsTable: items.length ? `partner_${t.id}_items` : null,
    columns: profile.map(r => ({ k: colName(r.field_key), label: r.label, type: r.sql_type, req: r.required || undefined })),
    itemColumns: items.map(r => ({ k: colName(r.field_key), label: r.label, type: r.sql_type })),
  }
}
writeFileSync(RUNTIME, `/* GENERATED by scripts/build-trade-profile-schema.mjs — do not edit.
 *
 * trade id -> its typed profile table, its catalogue child table, and the
 * columns to show. An explicit allowlist: a trade absent here has no
 * workspace, so no table name is ever assembled from user input.
 */
export const TRADE_PROFILE_SCHEMA = ${JSON.stringify(compact, null, 2)}

export const TRADE_IDS = Object.keys(TRADE_PROFILE_SCHEMA)
export const schemaFor = id => TRADE_PROFILE_SCHEMA[id] ?? null
`)
console.log(`runtime config    : src/config/tradeProfileSchema.js (${Object.keys(compact).length} trades)`)

console.log(`trades with profile questions : ${trades.length}`)
if (skipped.length) console.log(`skipped (no spec questions)   : ${skipped.join(', ')}`)
console.log(`catalogue child tables        : ${MAP.trades.filter(t => t.rows.some(r => r.section_kind === 'catalogue')).length}`)
console.log(`\nparts written:`)
for (const w of written) console.log(`  ${w.file}  —  ${w.trades} trades, ${w.tables} tables`)
console.log(`\ntotal tables: ${written.reduce((a, w) => a + w.tables, 0)}`)
