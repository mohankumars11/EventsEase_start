#!/usr/bin/env node
/**
 * Pack every migration into a few files you can paste into a fresh
 * Supabase project.
 *
 *   node scripts/build-sandbox-sql.mjs
 *
 * ══════════════════════════════════════════════════════════════════════
 * WHY
 * ══════════════════════════════════════════════════════════════════════
 *
 * There are 89 migrations and they are applied by hand. Applying them by
 * hand 89 times to stand up a second environment is how a second
 * environment never gets stood up — which is exactly the position this
 * project has been in, with one database serving both real customers and
 * every test anybody runs.
 *
 * So they are concatenated in numeric order into a small number of
 * parts, each with a header saying what it contains and where it stops.
 * A fresh project needs them run in order, once.
 *
 * ── Why parts and not one file ──────────────────────────────────────
 * The Supabase SQL editor is a browser textarea. 1.2 MB of SQL in one
 * paste is slow at best and silently truncated at worst, and a
 * half-applied schema is worse than none. Parts of roughly 250 KB paste
 * and run cleanly, and if one fails the header tells you exactly which
 * migrations were in it.
 *
 * ── Order is the whole contract ─────────────────────────────────────
 * Numeric, always. 057 creates PostGIS and the geography columns; 072
 * defines create_booking_request; 086 rewrites match_partners; 088
 * widens a CHECK that 058 created. Run out of order and the failures are
 * confusing rather than obvious.
 *
 * The files are generated. Never edit them — edit the migration and run
 * this again.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { ROOT } from './lib/loadSrc.mjs'

const SRC = join(ROOT, 'supabase', 'migrations')
const OUT = join(ROOT, 'supabase', 'sandbox')

/* Roughly a quarter of a megabyte per part. Not a hard limit — a part
   never splits a migration, so the last one in a part can push it over.
   A migration is atomic here: half of one is not a thing that can run. */
const TARGET_BYTES = 250_000

const files = readdirSync(SRC)
  .filter(f => /^\d{3}_.*\.sql$/.test(f))
  .sort((a, b) => Number(a.slice(0, 3)) - Number(b.slice(0, 3)))

if (!files.length) {
  console.error('\n  No migrations found in supabase/migrations/\n')
  process.exit(1)
}

// Regenerated wholesale, so a deleted migration cannot linger in a part.
if (existsSync(OUT)) rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })

const parts = []
let current = []
let size = 0

for (const f of files) {
  const body = readFileSync(join(SRC, f), 'utf8')
  current.push({ name: f, body })
  size += Buffer.byteLength(body)
  if (size >= TARGET_BYTES) { parts.push(current); current = []; size = 0 }
}
if (current.length) parts.push(current)

const pad = n => String(n).padStart(2, '0')
const rule = '-- ' + '═'.repeat(68)

parts.forEach((part, i) => {
  const n = i + 1
  const first = part[0].name.slice(0, 3)
  const last = part[part.length - 1].name.slice(0, 3)

  const head = [
    rule,
    `-- SANDBOX SCHEMA · part ${pad(n)} of ${pad(parts.length)} · migrations ${first}-${last}`,
    rule,
    '--',
    '-- GENERATED by scripts/build-sandbox-sql.mjs. Do not edit: edit the',
    '-- migration in supabase/migrations/ and run that script again.',
    '--',
    '-- Run the parts IN ORDER, in the Supabase SQL editor of a NEW,',
    '-- EMPTY project. Order is the contract: 057 creates PostGIS, 072',
    '-- defines create_booking_request, 086 rewrites match_partners, 088',
    '-- widens a CHECK that 058 created.',
    '--',
    `-- This part contains ${part.length} migration(s):`,
    ...part.map(p => `--   ${p.name}`),
    rule,
    '',
    '',
  ].join('\n')

  const body = part.map(p => [
    '',
    rule,
    `-- ${p.name}`,
    rule,
    '',
    p.body.replace(/\r\n/g, '\n').trimEnd(),
    '',
  ].join('\n')).join('\n')

  const out = join(OUT, `part-${pad(n)}_${first}-${last}.sql`)
  writeFileSync(out, head + body + '\n', 'utf8')
  const kb = Math.round(Buffer.byteLength(head + body) / 1024)
  console.log(`  part-${pad(n)}_${first}-${last}.sql   ${String(part.length).padStart(2)} migrations   ${String(kb).padStart(4)} KB`)
})

console.log(`\n  ${files.length} migrations -> ${parts.length} parts in supabase/sandbox/\n`)
