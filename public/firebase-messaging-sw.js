/* Background push for the partner app.
 *
 * ── Why this file is plain JS with hardcoded-looking config ──────────
 * A service worker runs outside the page and outside the bundler. It
 * cannot read `import.meta.env`, cannot import from `src/`, and is
 * fetched by the browser as a static file from the site root. So the
 * Firebase config is passed in on the registration URL as query
 * parameters by src/lib/push.js, and read here from `location.search`.
 *
 * None of those values are secret. The Firebase web config is public by
 * design — it identifies the project, it does not authorise anything. The
 * key that DOES authorise sending lives in FIREBASE_SERVICE_ACCOUNT on
 * the server and never reaches a browser.
 *
 * ── Scope ────────────────────────────────────────────────────────────
 * Registered at /firebase-cloud-messaging-push-scope, NOT at /. The PWA
 * service worker generated by vite-plugin-pwa owns the root scope, and a
 * second worker registered there would replace it — taking the app's
 * offline behaviour with it.
 */
importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-app-compat.js')
importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-messaging-compat.js')

const params = new URLSearchParams(self.location.search)

/* Baked in at build time, and the query string is only a fallback.
 *
 * ══════════════════════════════════════════════════════════════════════
 * WHY THE URL WAS THE WRONG PLACE TO KEEP THIS
 * ══════════════════════════════════════════════════════════════════════
 *
 * The config used to arrive ONLY as query parameters on the
 * registration URL. That works exactly once, on a browser that has
 * never seen this worker: after that, whether `self.location.search`
 * still carries them depends on which registration the browser decides
 * to reuse, and a worker previously registered without them keeps
 * serving from that URL.
 *
 * When it goes wrong there is no error anywhere. `config.apiKey` is
 * null, the `if` below is skipped, `onBackgroundMessage` is never
 * attached — and FCM still delivers the push. The browser receives a
 * message no handler claims and shows nothing at all, while every
 * server-side signal says the send succeeded.
 *
 * That is precisely the shape of "no notification arrived, and nothing
 * anywhere says why".
 *
 * `scripts/write-sw-config.mjs` writes the values below into dist/ at
 * build time from the same VITE_FIREBASE_* variables the app uses, so
 * the worker is self-sufficient. The placeholder is what ships in the
 * repo; a build always replaces it.
 *
 * None of it is secret — the Firebase web config identifies the project
 * and authorises nothing. Sending is authorised by
 * FIREBASE_SERVICE_ACCOUNT, on the server, which never reaches a
 * browser.
 */
const BAKED = '__FIREBASE_SW_CONFIG__'

const baked = (() => {
  try {
    return BAKED.startsWith('__') ? null : JSON.parse(atob(BAKED))
  } catch { return null }
})()

const config = {
  apiKey:            params.get('apiKey')    || baked?.apiKey,
  authDomain:        params.get('authDomain')|| baked?.authDomain,
  projectId:         params.get('projectId') || baked?.projectId,
  messagingSenderId: params.get('senderId')  || baked?.messagingSenderId,
  appId:             params.get('appId')     || baked?.appId,
}

if (config.apiKey && config.projectId) {
  firebase.initializeApp(config)
  const messaging = firebase.messaging()

  /* A job offer, arriving while the app is closed.
   *
   * This is the entire reason push exists here: a master has 45 seconds
   * to answer, and without this the offer expires unseen while the
   * customer's screen says "still looking".
   */
  messaging.onBackgroundMessage(payload => {
    const d = payload.data || {}

    const title = d.title || 'New job'
    const options = {
      body: d.body || '',
      icon: '/icon-512.png',
      badge: '/icon-512.png',
      // Collapses to one notification per line rather than stacking a
      // separate banner for every wave of the same job.
      tag: d.lineId || 'sambramo-job',
      renotify: true,
      // A job is time-limited and worth a buzz; nothing else here is.
      requireInteraction: false,
      vibrate: [120, 60, 120],
      data: { url: d.url || '/dashboard/vendor' },
      actions: [{ action: 'open', title: 'See the job' }],
    }

    return self.registration.showNotification(title, options)
  })
}

/* Tapping the notification focuses an open tab rather than opening a
 * second one — a master with the app already open should not end up with
 * two copies of it fighting over the same offer. */
self.addEventListener('notificationclick', event => {
  event.notification.close()
  const url = event.notification?.data?.url || '/dashboard/vendor'

  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(list => {
      for (const client of list) {
        if ('focus' in client) {
          client.navigate?.(url)
          return client.focus()
        }
      }
      return self.clients.openWindow?.(url)
    }),
  )
})
